#!/usr/bin/env python3
"""Write `rustyzoo-android/.cargo/config.toml` for the Android link.

Rust's linker here is bare `clang.exe` (Rust uses CreateProcess, which cannot run the NDK's
`.cmd` shims). Everything that linker needs therefore has to be passed as flags:

  --target=<triple><api>  the NDK triple with the API level; Rust passes none, and without it
                          clang picks the host target and the linker rejects the Android flags
  -L<sysroot lib>         where libc++_static.a lives
  -lc++_static -lc++abi -lunwind
                          the static C++ runtime SDL3's C++ sources need. Without it,
                          librustyzoo.so keeps __gxx_personality_v0 undefined and Android's
                          dlopen fails with `cannot locate symbol "__gxx_personality_v0"`.

They go in a `.cargo/config.toml` rather than `CARGO_TARGET_<TRIPLE>_RUSTFLAGS`, because the
environment variable *replaces* cargo's own flags (the build then fails with "can't find crate
for `std`"), while the file's `rustflags` are added to them.

Usage: python write-cargo-config.py <ndk-home> <api>
"""

import os
import sys


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: write-cargo-config.py <ndk-home> <api>", file=sys.stderr)
        return 2
    ndk_home, api = sys.argv[1], sys.argv[2]

    here = os.path.dirname(os.path.abspath(__file__))

    sysroot_lib_plain = os.path.join(
        ndk_home,
        "toolchains", "llvm", "prebuilt", "windows-x86_64",
        "sysroot", "usr", "lib", "aarch64-linux-android",
    )
    sysroot_lib = sysroot_lib_plain.replace("\\", "\\\\")

    # The API-level directory: it holds the libc.so stub, which the static directory above
    # does not. See the note in the generated file.
    api_lib = os.path.join(sysroot_lib_plain, api).replace("\\", "\\\\")

    # The clang_rt builtins archive. Its directory carries the clang major version, which moves
    # between NDK releases, so it is found by glob rather than hard-coded.
    builtins_dir = os.path.join(
        ndk_home, "toolchains", "llvm", "prebuilt", "windows-x86_64",
        "lib", "clang",
    )
    matches = []
    for root, _dirs, files in os.walk(builtins_dir):
        for name in files:
            if name == "libclang_rt.builtins-aarch64-android.a":
                matches.append(os.path.join(root, name))
    if not matches:
        print(f"write-cargo-config: no libclang_rt.builtins-aarch64-android.a under {builtins_dir}",
              file=sys.stderr)
        return 1
    builtins = matches[0].replace("\\", "\\\\")

    # The JNI surface SDL3 exposes to Java. Rust passes its own --version-script first on the
    # link line, and it marks every symbol rustc does not know about as `local` -- which hides
    # all 67 Java_org_libsdl_app_* entry points, so Android's very first lookup
    # (nativeGetVersion) raises UnsatisfiedLinkError. lld applies the *last* --version-script
    # it is given, so this file -- referenced from rustflags, which land at the end of the
    # command -- replaces Rust's and re-exports the JNI surface.
    #
    # Only globs and symbols that are certainly defined are listed: lld fails the link with
    # "version script assignment of 'global' to symbol X failed: symbol not defined" when a
    # name does not resolve, so JNI_OnLoad is covered by the JNI_* glob rather than by name.
    map_text = """\
{
  global:
    Java_*;
    JNI_*;
    SDL_main;
  local:
    *;
};
"""
    map_path = os.path.join(here, "rustyzoo-android", ".cargo", "jni-exports.map")
    os.makedirs(os.path.dirname(map_path), exist_ok=True)
    with open(map_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(map_text)
    version_script = map_path.replace("\\", "\\\\")

    text = f'''# Generated by android/write-cargo-config.py -- do not edit by hand.
#
# Link flags for the Android shell. They are *added* to what cargo passes; the environment
# variable CARGO_TARGET_<TRIPLE>_RUSTFLAGS would replace it instead, which breaks the build
# with "can't find crate for `std`".
#
# The linker is bare clang.exe (Rust cannot exec a .cmd shim), so it needs:
#   --target=<triple><api>  the NDK triple with the API level
#   -L<sysroot lib>         where libc++_static.a lives
#   -lc++_static -lc++abi -lunwind   the static C++ runtime SDL3's C++ sources need
#
# Without the last line, librustyzoo.so keeps __gxx_personality_v0 undefined and Android's
# dlopen fails with `cannot locate symbol "__gxx_personality_v0"`.
#
# --allow-multiple-definition: NDK 30's libc.a embeds a prebuilt Rust std
# (librustlibs.libstd.std.*.o) that also defines rust_eh_personality. Rust's own libstd is
# linked first, so its definition wins; without the flag lld reports a duplicate symbol.
#
# The clang_rt builtins archive is passed as a file, not -l: it defines __arm_za_disable, which
# NDK 30's libc.a (clone.o, setjmp.o, vfork.o) references. Rust's link line has -nodefaultlibs,
# so the driver never adds it, and the symbol stays undefined -- Android's dlopen then fails
# with `cannot locate symbol "__arm_za_disable"`.
#
# The last four flags force libc to be linked dynamically. Rust emits its own -lc/-lm/-ldl
# under -Wl,-Bdynamic, but lld resolves a -l per directory: it tries lib<name>.so and then
# lib<name>.a *in that directory* before moving on. The sysroot's static directory (which holds
# libc.a) must therefore not precede the API-level directory (which holds libc.so) in the search
# path, or -lc binds to the static bionic copy. That copy is unusable from a shared library: its
# __libc_shared_globals is never initialized, so getauxval dereferences a null auxv and the
# process dies with SIGSEGV during SDL_main startup. -Bdynamic plus the API-level directory
# makes -lc resolve to the shared library; --no-as-needed keeps it in DT_NEEDED.
# The static directory is deliberately NOT passed with -L: the clang driver adds it itself,
# after the API-level one, which is exactly the order needed for libc++_static.a to still be
# found while libc resolves to libc.so.
#
# --no-gc-sections: SDL3 is built with -ffunction-sections, so every JNI entry point sits in
# its own .text.Java_* section. Nothing in the Rust code references them -- they are called
# from Java by name -- so rustc's --gc-sections drops them before the version script below can
# matter. Disabling collection keeps them; it costs a little size and nothing else, because
# rustc's own dead-code elimination has already run at the Rust level.
#
# --version-script=<jni-exports.map>: see the note where that file is written. It replaces
# Rust's own script, which would otherwise keep the JNI entry points local.

[target.aarch64-linux-android]
rustflags = [
    "-C", "link-arg=--target=aarch64-linux-android{api}",
    "-C", "link-arg=-lc++_static",
    "-C", "link-arg=-lc++abi",
    "-C", "link-arg=-lunwind",
    "-C", "link-arg=-Wl,--allow-multiple-definition",
    "-C", "link-arg=-Wl,-Bdynamic",
    "-C", "link-arg=-L{api_lib}",
    "-C", "link-arg=-Wl,--no-as-needed",
    "-C", "link-arg=-lc",
    "-C", "link-arg=-Wl,--no-gc-sections",
    "-C", "link-arg=-Wl,--version-script={version_script}",
    "-C", "link-arg={builtins}",
]
'''

    here = os.path.dirname(os.path.abspath(__file__))
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "rustyzoo-android", ".cargo", "config.toml")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"write-cargo-config: wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
